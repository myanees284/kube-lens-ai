import { describe, expect, it } from "vitest";
import type { InvestigationSseEvent } from "@kube-lens/contracts";
import {
  canIngest,
  displayedStatus,
  elapsedLabel,
  missedEarlierEvents,
  retrievalPresentation,
  sourcePresentation,
  timelineText,
  upsertTimeline,
} from "./present.ts";

function event(sequence: number, message = "ok"): InvestigationSseEvent {
  return {
    schemaVersion: 1,
    investigationId: "a".repeat(24),
    sequence,
    timestamp: "2026-10-25T10:00:00.000Z",
    message,
  };
}

describe("investigation presentation", () => {
  it("labels a stored RCA and a Groq RCA separately", () => {
    expect(sourcePresentation("historical_incident").title).toBe("Stored incident");
    expect(sourcePresentation("groq").title).toBe("Generated by Groq");
    expect(sourcePresentation("groq").detail).toContain("external provider");
  });

  it("describes a failed knowledge check as unavailable", () => {
    const failed = retrievalPresentation("retrieval_failed");
    expect(failed.unavailable).toBe(true);
    expect(failed.title).toBe("Knowledge check unavailable");
    expect(failed.detail).toBe("Historical incident knowledge could not be checked.");
    expect(retrievalPresentation("groq_fallback").unavailable).toBe(false);
    expect(retrievalPresentation("historical_match").title).toBe("Stored incident matched");
  });

  it("allows ingestion only for a finished RCA that is not already saved", () => {
    const base = {
      rca: { source: "groq" as const, summary: "s", rootCause: "r", recommendations: [], limitations: [], references: [] },
      ingestion: { status: "not_requested" as const },
    };
    expect(canIngest({ ...base, status: "partial" })).toBe(true);
    expect(canIngest({ ...base, status: "completed" })).toBe(true);
    expect(canIngest({ ...base, status: "failed" })).toBe(false);
    expect(canIngest({ ...base, status: "completed", rca: undefined })).toBe(false);
    expect(canIngest({ ...base, status: "completed", ingestion: { status: "succeeded" } })).toBe(false);
  });

  it("keeps timeline events ordered and shows retrieval provenance", () => {
    const first = upsertTimeline([], { type: "step.completed", event: event(2, "later") });
    const both = upsertTimeline(first, { type: "investigation.started", event: event(1, "started") });
    expect(both.map((entry) => entry.event.sequence)).toEqual([1, 2]);
    expect(missedEarlierEvents(both)).toBe(false);
    expect(missedEarlierEvents(first)).toBe(true);

    const retrieval = timelineText({
      type: "retrieval.completed",
      event: { ...event(3), payload: { decision: "retrieval_failed" } },
    });
    expect(retrieval).toBe("Knowledge check unavailable");
    expect(elapsedLabel("2026-10-25T10:00:00.000Z", "2026-10-25T10:00:12.000Z", 0)).toBe("12s");
  });

  it("shows a queued investigation as running once progress events arrive", () => {
    expect(displayedStatus("queued", [])).toBe("queued");
    expect(displayedStatus("queued", [{ type: "investigation.started", event: event(1) }])).toBe("running");
    expect(displayedStatus("queued", [{ type: "investigation.partial", event: event(2) }])).toBe("partial");
  });
});
