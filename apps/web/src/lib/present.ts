import type { InvestigationResponse, InvestigationSseEvent } from "@kube-lens/contracts";

export interface TimelineEntry {
  type: string;
  event: InvestigationSseEvent;
}

const stageLabels: Record<string, string> = {
  collecting_evidence: "Collecting evidence",
  preparing_evidence: "Preparing evidence",
  retrieving_knowledge: "Checking stored knowledge",
  using_historical_rca: "Using a stored RCA",
  generating_rca: "Asking Groq",
  persisting_result: "Saving the result",
};

export function stageLabel(step: string | undefined): string {
  if (!step) return "Investigation";
  return stageLabels[step] ?? step.replaceAll("_", " ");
}

export function displayedStatus(
  status: InvestigationResponse["status"],
  events: TimelineEntry[],
): InvestigationResponse["status"] {
  for (let index = events.length - 1; index >= 0; index -= 1) {
    const entry = events[index];
    if (entry?.type === "investigation.completed") return "completed";
    if (entry?.type === "investigation.partial") return "partial";
    if (entry?.type === "investigation.failed") return "failed";
  }
  if (status === "queued" && events.length > 0) return "running";
  return status;
}

export function statusLabel(status: InvestigationResponse["status"]): string {
  switch (status) {
    case "queued":
      return "Queued";
    case "running":
      return "Running";
    case "completed":
      return "Completed";
    case "partial":
      return "Partial";
    case "failed":
      return "Failed";
  }
}

export function sourcePresentation(source: "historical_incident" | "groq"): { title: string; detail: string } {
  if (source === "historical_incident") {
    return {
      title: "Stored incident",
      detail: "This root cause comes from a stored incident.",
    };
  }
  return {
    title: "Generated by Groq",
    detail: "Groq, an external provider, wrote this root cause from the sanitized evidence. Treat the recommendations as suggestions.",
  };
}

export function retrievalPresentation(decision: "historical_match" | "groq_fallback" | "retrieval_failed"): {
  title: string;
  detail: string;
  unavailable: boolean;
} {
  switch (decision) {
    case "historical_match":
      return {
        title: "Stored incident matched",
        detail: "Retrieval selected a stored incident for this evidence.",
        unavailable: false,
      };
    case "groq_fallback":
      return {
        title: "No stored RCA selected",
        detail: "Retrieval finished without selecting a stored incident.",
        unavailable: false,
      };
    case "retrieval_failed":
      return {
        title: "Knowledge check unavailable",
        detail: "Historical incident knowledge could not be checked.",
        unavailable: true,
      };
  }
}

export function canIngest(investigation: Pick<InvestigationResponse, "status" | "rca" | "ingestion">): boolean {
  return (
    (investigation.status === "completed" || investigation.status === "partial") &&
    investigation.rca !== undefined &&
    investigation.ingestion.status !== "succeeded"
  );
}

export function elapsedLabel(createdAt: string, completedAt: string | undefined, now: number): string {
  const start = Date.parse(createdAt);
  const end = completedAt ? Date.parse(completedAt) : now;
  if (Number.isNaN(start) || Number.isNaN(end)) return "";
  const seconds = Math.max(0, Math.round((end - start) / 1000));
  const minutes = Math.floor(seconds / 60);
  const remainder = seconds % 60;
  return minutes > 0 ? `${minutes}m ${remainder}s` : `${seconds}s`;
}

export function timelineText(entry: TimelineEntry): string {
  const payload = entry.event.payload;
  if (entry.type === "retrieval.completed" && isRecord(payload) && typeof payload.decision === "string") {
    if (payload.decision === "historical_match" || payload.decision === "groq_fallback" || payload.decision === "retrieval_failed") {
      return retrievalPresentation(payload.decision).title;
    }
  }
  if (entry.type === "rca.completed" && isRecord(payload)) {
    if (payload.source === "historical_incident" || payload.source === "groq") {
      return sourcePresentation(payload.source).title;
    }
  }
  if (entry.type === "evidence.summary" && isRecord(payload) && typeof payload.summary === "string") {
    return payload.summary;
  }
  return entry.event.message ?? stageLabel(entry.event.step);
}

export function upsertTimeline(current: TimelineEntry[], entry: TimelineEntry): TimelineEntry[] {
  const next = current.filter((item) => item.event.sequence !== entry.event.sequence);
  next.push(entry);
  next.sort((left, right) => left.event.sequence - right.event.sequence);
  return next;
}

export function missedEarlierEvents(events: TimelineEntry[]): boolean {
  const first = events[0];
  return first !== undefined && first.event.sequence > 1;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null;
}
